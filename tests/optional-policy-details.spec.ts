import { test, expect } from '@playwright/test';
import { ConvexHttpClient } from 'convex/browser';
import { api } from '../convex/_generated/api';
import { readFileSync } from 'node:fs';
const newAddress = 'http://127.0.0.1:5173/#check=new-policy';
const oldAddress = 'http://127.0.0.1:5173/#check=old-policy';
const oldKey = '4a214cc491d981a58e827323872b4511f63dfa5b69deb5fbe48588a923775043';
const newKey = '1c57bb11444c1f1ca6609fe657c570618260b50d8d4fc7fd2caa6feaa9ebc498';
const url = readFileSync('.env.local', 'utf8').match(/^CONVEX_URL=(.+)$/m)![1].trim();
const client = new ConvexHttpClient(url);
test('new policy saves optional details, hides cleared details and reopens with all details', async ({ page }) => {
 test.setTimeout(60000);
 const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
 await page.goto(newAddress);
 await page.getByLabel('Insurer', { exact: true }).fill('LIC');
 await page.getByLabel('Policy number', { exact: true }).fill('DEMO-OPTIONAL-001');
 await page.getByLabel('Policy type', { exact: true }).selectOption('Life insurance');
 await page.getByLabel('Nominee(s)', { exact: true }).fill('Demo Family Member');
 await page.getByLabel('Where the physical papers are kept').fill('Blue folder, bedroom cupboard, top shelf');
 await page.getByLabel('Servicing branch or agent name (optional)', { exact: true }).fill('Demo LIC branch, Bengaluru');
 await page.getByLabel('Branch or agent phone number (optional)', { exact: true }).fill('+91 00000 00000');
 await page.getByLabel('Sum assured in rupees (optional)', { exact: true }).fill('1000000');
 await page.getByLabel('A personal note to my family (optional)', { exact: true }).fill('Please take your time. The blue folder has everything you need.\nWith love, always.');
 const family = page.getByRole('region', { name: 'For my family' });
 const contact = family.getByRole('listitem').filter({ has: page.getByRole('heading', { name: 'Contact LIC', exact: true }) });
 await expect(contact).toContainText('Demo LIC branch, Bengaluru');
 await expect(contact.getByRole('link', { name: '+91 00000 00000', exact: true })).toHaveAttribute('href', 'tel:+910000000000');
 await expect(family.locator('dl')).toContainText('₹10,00,000');
 await expect(family.locator('.personal-note')).toContainText('With love, always.');
 expect(await family.evaluate(el => { const note = el.querySelector('.personal-note')!; const details = el.querySelector('dl')!; return Boolean(note.compareDocumentPosition(details) & Node.DOCUMENT_POSITION_FOLLOWING); })).toBe(true);
 await expect(family.getByRole('listitem')).toHaveCount(4);
 await page.getByRole('button', { name: 'Save policy', exact: true }).click();
 await expect(page.getByRole('status')).toContainText('Policy saved.');
 await page.reload(); await expect(page.getByLabel('Sum assured in rupees (optional)', { exact: true })).toHaveValue('1000000');
 const saved = await client.query(api.policies.get, { browserKey: newKey });
 expect(saved?.sumAssured).toBe(1000000); expect(saved?.servicingName).toBe('Demo LIC branch, Bengaluru'); expect(saved?.servicingPhone).toBe('+91 00000 00000'); expect(saved?.personalNote).toContain('With love, always.');
 for (const label of ['Servicing branch or agent name (optional)', 'Branch or agent phone number (optional)', 'Sum assured in rupees (optional)', 'A personal note to my family (optional)']) await page.getByLabel(label, { exact: true }).fill('');
 await page.getByRole('button', { name: 'Save policy', exact: true }).click(); await expect(page.getByRole('status')).toContainText('Policy saved.');
 await page.reload(); await expect(page.getByLabel('Insurer', { exact: true })).toHaveValue('LIC');
 await expect(family.locator('.personal-note')).toHaveCount(0); await expect(family.locator('.servicing-contact')).toHaveCount(0); await expect(family.locator('dl')).not.toContainText('Sum assured');
 const cleared = await client.query(api.policies.get, { browserKey: newKey });
 for (const key of ['servicingName', 'servicingPhone', 'sumAssured', 'personalNote']) expect(cleared).not.toHaveProperty(key);
 await page.getByLabel('Servicing branch or agent name (optional)', { exact: true }).fill('Demo LIC branch, Bengaluru');
 await page.getByLabel('Branch or agent phone number (optional)', { exact: true }).fill('+91 00000 00000');
 await page.getByLabel('Sum assured in rupees (optional)', { exact: true }).fill('1000000');
 await page.getByLabel('A personal note to my family (optional)', { exact: true }).fill('Please take your time. The blue folder has everything you need.\nWith love, always.');
 await page.getByRole('button', { name: 'Save policy', exact: true }).click(); await expect(page.getByRole('status')).toContainText('Policy saved.'); await page.reload();
 await expect(family.locator('.personal-note')).toContainText('With love, always.');
 await page.screenshot({ path: 'verification/new-policy-desktop.png', fullPage: true });
 await page.setViewportSize({ width: 390, height: 844 }); await page.screenshot({ path: 'verification/new-policy-mobile.png', fullPage: true });
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
 expect(errors).toEqual([]);
 console.log('NEW POLICY PAGE: ' + newAddress);
 console.log('Verified Convex values: agent=Demo LIC branch, Bengaluru; phone=+91 00000 00000; sumAssured=1000000; personal note saved.');
 console.log('Verified: live preview, contact placement, rupee formatting, note placement, save, reload, clearing optional fields and mobile width.');
});
test('policy saved before this change opens without optional fields or errors', async ({ page }) => {
 const before = await client.query(api.policies.get, { browserKey: oldKey });
 expect(before?.policyNumber).toBe('DEMO-002');
 for (const key of ['servicingName', 'servicingPhone', 'sumAssured', 'personalNote']) expect(before).not.toHaveProperty(key);
 const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
 await page.goto(oldAddress); await expect(page.getByLabel('Policy number', { exact: true })).toHaveValue('DEMO-002');
 for (const label of ['Servicing branch or agent name (optional)', 'Branch or agent phone number (optional)', 'Sum assured in rupees (optional)', 'A personal note to my family (optional)']) await expect(page.getByLabel(label, { exact: true })).toHaveValue('');
 const family = page.getByRole('region', { name: 'For my family' });
 await expect(family.locator('.personal-note')).toHaveCount(0); await expect(family.locator('.servicing-contact')).toHaveCount(0); await expect(family.locator('dl')).not.toContainText('Sum assured'); await expect(family.getByRole('listitem')).toHaveCount(4);
 await expect(page.getByText('Saved in Convex', { exact: true })).toBeVisible();
 await page.screenshot({ path: 'verification/old-policy-desktop.png', fullPage: true });
 await page.reload(); await expect(page.getByLabel('Policy number', { exact: true })).toHaveValue('DEMO-002');
 expect(await client.query(api.policies.get, { browserKey: oldKey })).toEqual(before);
 expect(errors).toEqual([]);
 console.log('OLD POLICY PAGE: ' + oldAddress);
 console.log('Verified: existing DEMO-002 record has no new fields; it opens and reloads unchanged, hides empty optional details and keeps all four claim steps.');
});
