async function signup(page:Page,email:string){
  await page.getByLabel('Email address',{exact:true}).fill(email);
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Create account',exact:true}).click();
}
async function clientFor(page:Page){
  const token=await page.evaluate(()=>{const key=Object.keys(localStorage).find(k=>k.startsWith('__convexAuthJWT'));return key?localStorage.getItem(key):null;});
  expect(token).toBeTruthy();const client=new ConvexHttpClient(url);client.setAuth(token!);return client;
}
